def status_badge(language: str, status: str) -> str:
    icon = STATUS_ICONS.get(status, "⚪")
    label = t(language, STATUS_KEYS.get(status, "status_pending"))
    return f"{icon} {label}"


def t(language: str, key: str, **values: object) -> str:
    localized = TEXTS.get(language, TEXTS["ru"])
    template = localized.get(key, TEXTS["ru"].get(key, key))
    return template.format(**values) if values else template


def selected_fuel_types(value: str | None) -> tuple[str, ...]:
    if not value:
        return ()
    return tuple(
        dict.fromkeys(
            fuel for fuel in value.split("+") if fuel in FUEL_KEYS
        )
    )


def fuel_label(language: str, value: str | None) -> str:
    fuels = selected_fuel_types(value)
    if not fuels:
        return t(language, "fuel_any")
    return " + ".join(t(language, FUEL_KEYS[fuel]) for fuel in fuels)
