def status_badge(language: str, status: str) -> str:
    icon = STATUS_ICONS.get(status, "⚪")
    label = t(language, STATUS_KEYS.get(status, "status_pending"))
    return f"{icon} {label}"


def t(language: str, key: str, **values: object) -> str:
    localized = TEXTS.get(language, TEXTS["ru"])
    template = localized.get(key, TEXTS["ru"].get(key, key))
    return template.format(**values) if values else template
